#!/usr/bin/env python3
"""Generate one GitHub Pages URL for every challenge record."""
from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_FILE = ROOT / "data" / "challenges.json"
TEMPLATE_FILE = ROOT / "challenge-template.html"
OUTPUT_ROOT = ROOT / "challenges"
GENERATED_MARKER = "<!-- GENERATED BY scripts/generate_challenge_pages.py -->"
SAFE_ID = re.compile(r"^[A-Za-z0-9_-]+$")


def main() -> None:
    if not DATA_FILE.is_file():
        raise SystemExit(f"Challenge data file not found: {DATA_FILE}")
    if not TEMPLATE_FILE.is_file():
        raise SystemExit(f"Challenge page template not found: {TEMPLATE_FILE}")

    data = json.loads(DATA_FILE.read_text(encoding="utf-8"))
    records = data.get("challenges", [])
    if not isinstance(records, list):
        raise SystemExit("'challenges' must be a JSON array")

    template = TEMPLATE_FILE.read_text(encoding="utf-8")
    if template.count("__CHALLENGE_ID_JSON__") != 1:
        raise SystemExit("Challenge template must contain exactly one ID placeholder")

    ids: list[str] = []
    for record in records:
        if not isinstance(record, dict) or record.get("id") is None:
            raise SystemExit("Every challenge must be an object with a non-empty id")
        challenge_id = str(record["id"]).strip()
        if not challenge_id or not SAFE_ID.fullmatch(challenge_id):
            raise SystemExit(f"Unsafe or empty challenge ID: {challenge_id!r}")
        if challenge_id in ids:
            raise SystemExit(f"Duplicate challenge ID: {challenge_id}")
        ids.append(challenge_id)

    # Remove only pages previously generated by this script. Leave hand-authored
    # content inside the challenges directory untouched.
    if OUTPUT_ROOT.exists():
        for entry in OUTPUT_ROOT.iterdir():
            page = entry / "index.html"
            if entry.is_dir() and page.is_file():
                if GENERATED_MARKER in page.read_text(encoding="utf-8"):
                    shutil.rmtree(entry)

    for challenge_id in ids:
        page_dir = OUTPUT_ROOT / challenge_id
        page_dir.mkdir(parents=True, exist_ok=True)
        page_html = template.replace(
            "__CHALLENGE_ID_JSON__", json.dumps(challenge_id, ensure_ascii=True)
        )
        (page_dir / "index.html").write_text(page_html, encoding="utf-8")

    print(f"Generated {len(ids)} individual challenge page(s).")
    for challenge_id in ids:
        print(f"  /challenges/{challenge_id}/")


if __name__ == "__main__":
    main()
